require_once __DIR__ . '/../config/db.php';

// Variables to store feedback messages for the visitor
$success_message = '';
$error_message = '';

// 1. Process form submission when HTTP method is POST
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    // Collect and trim user input
    $name = trim($_POST['name'] ?? '');
    $nic = trim($_POST['nic'] ?? '');
    $phone = trim($_POST['phone'] ?? '');
    $email = trim($_POST['email'] ?? '');
    $host_id = trim($_POST['host_id'] ?? '');
    $purpose = trim($_POST['purpose'] ?? '');
    $expected_date = trim($_POST['expected_date'] ?? '');
    $expected_time = trim($_POST['expected_time'] ?? '');

    // Basic server-side validation (never trust client-side validation alone)

    if (empty($name) || empty($nic) || empty($email) || empty($host_id) || empty($purpose) || empty($expected_date) || empty($expected_time)) {
        $error_message = 'Please fill in all required fields.';
    } elseif (!filter_var($email, FILTER_VALIDATE_EMAIL)) {
        $error_message = 'Please enter a valid email address.';
    } elseif (!preg_match('/^([0-9]{9}[vVxX]|[0-9]{12})$/', $nic)) {
        // Enforces: 9 digits ending in V/v (or X/x), OR exactly 12 digits (Max 12 chars)
        $error_message = 'Invalid NIC format. Enter 9 digits followed by V (e.g., 123456789V) or 12 digits.';
    } elseif ($phone !== '' && !preg_match('/^0[0-9]{9}$/', $phone)) {
        // Enforces: Starts with 0 followed by exactly 9 digits (10 digits total)
        $error_message = 'Phone number must be exactly 10 digits starting with 0 (e.g., 0771234567).';
    } else {

        // Combine date and time into standard SQL DATETIME format (YYYY-MM-DD HH:MM:SS)
        $expected_visit_at = $expected_date . ' ' . $expected_time . ':00';

        try {
            // Start a transaction: both visitor and request must succeed together
            $pdo->beginTransaction();

            // STEP A: Check if this visitor already exists by NIC (Option 1)
            $checkVisitorStmt = $pdo->prepare("SELECT visitor_id FROM visitors WHERE nic = ?");
            $checkVisitorStmt->execute([$nic]);
            $existingVisitor = $checkVisitorStmt->fetch();

            if ($existingVisitor) {
                // Reuse existing visitor ID
                $visitor_id = $existingVisitor['visitor_id'];

                // Update contact details in case phone, email or name changed
                $updateVisitorStmt = $pdo->prepare(
                    "UPDATE visitors SET name = ?, phone = ?, email = ? WHERE visitor_id = ?"
                );
                // Convert empty phone string to NULL for database cleanliness
                $updateVisitorStmt->execute([$name, $phone !== '' ? $phone : null, $email, $visitor_id]);
            } else {
                // New visitor: insert fresh row
                $insertVisitorStmt = $pdo->prepare(
                    "INSERT INTO visitors (name, nic, phone, email) VALUES (?, ?, ?, ?)"
                );
                $insertVisitorStmt->execute([$name, $nic, $phone !== '' ? $phone : null, $email]);
                // Retrieve the auto-increment ID generated by MySQL
                $visitor_id = $pdo->lastInsertId();
            }

            // STEP B: Insert the visit request linked to the visitor
            $insertRequestStmt = $pdo->prepare(
                "INSERT INTO visit_requests (visitor_id, host_id, purpose, expected_visit_at, status) 
                 VALUES (?, ?, ?, ?, 'pending')"
            );
            $insertRequestStmt->execute([$visitor_id, $host_id, $purpose, $expected_visit_at]);

            // If we reached here without errors, permanently commit the transaction
            $pdo->commit();

            $success_message = 'Your visit request has been submitted successfully! The host will review it shortly.';
        } catch (Exception $e) {
            // If any query failed, undo all changes made during this transaction
            if ($pdo->inTransaction()) {
                $pdo->rollBack();
            }
            $error_message = 'An error occurred while submitting your request: ' . $e->getMessage();
        }
    }
}

// 2. Fetch hosts to populate the dropdown
try {
    $stmt = $pdo->query("SELECT host_id, name FROM hosts ORDER BY name ASC");
    $hosts = $stmt->fetchAll();
} catch (PDOException $e) {
    exit('Could not load host directory: ' . $e->getMessage());
}
